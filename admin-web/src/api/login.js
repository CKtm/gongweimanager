import request from '@/utils/request'

// 登录方法
export function login(username, password, code, uuid) {
  const data = {
    username,
    password,
    code,
    uuid
  }
  return request({
    url: '/login',
    headers: {
      isToken: false,
      repeatSubmit: false
    },
    method: 'post',
    data: data
  })
}

// 首次登录使用一次性票据强制修改密码
export function forceResetPassword(resetToken, newPassword) {
  return request({
    url: '/forceResetPwd',
    headers: {
      isToken: false,
      repeatSubmit: false
    },
    method: 'post',
    data: { resetToken, newPassword }
  })
}

